// Generates extension/src/emoji-data.js from emojibase-data.
// Output shape: [[emoji, [shortcodes...], [search tags...]], ...] in emoji-picker order.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const emojis = require('emojibase-data/en/data.json');

// Earlier sets win when two sets give the same shortcode to different emoji.
// joypixels and github are closest to the names people know from Discord/Slack.
const SETS = ['joypixels', 'github', 'iamcal', 'emojibase'];
const shortcodeSets = SETS.map((s) => require(`emojibase-data/en/shortcodes/${s}.json`));

const asArray = (v) => (v === undefined ? [] : Array.isArray(v) ? v : [v]);
const VALID_NAME = /^[a-z0-9_+-]+$/;
const FLAGS_GROUP = 9;

const owner = new Map(); // shortcode -> hexcode
for (const set of shortcodeSets) {
  for (const { hexcode } of emojis) {
    for (const raw of asArray(set[hexcode])) {
      const name = raw.toLowerCase();
      if (VALID_NAME.test(name) && !owner.has(name)) owner.set(name, hexcode);
    }
  }
}

const groupByHex = new Map(emojis.map((e) => [e.hexcode, e.group]));

const namesByHex = new Map();
for (const [name, hexcode] of owner) {
  // Bare country codes would hijack everyday prefixes: ":sm" must not mean San Marino.
  // The flags stay reachable as :flag_sm:.
  if (groupByHex.get(hexcode) === FLAGS_GROUP && name.length <= 2) continue;
  if (!namesByHex.has(hexcode)) namesByHex.set(hexcode, []);
  namesByHex.get(hexcode).push(name);
}

const rows = emojis
  .filter((e) => e.group !== undefined && e.group !== 2) // drop regional letters and skin-tone components
  .filter((e) => namesByHex.has(e.hexcode))
  .sort((a, b) => a.order - b.order)
  .map((e) => {
    const names = namesByHex.get(e.hexcode);
    const tags = (e.tags ?? [])
      .map((t) => t.toLowerCase())
      .filter((t) => VALID_NAME.test(t) && !names.includes(t));
    return [e.emoji, names, tags];
  });

const out = `// Generated by scripts/build-emoji-data.mjs. Do not edit by hand.\nglobalThis.COLON_EMOJI_DATA=${JSON.stringify(rows)};\n`;
writeFileSync(new URL('../extension/src/emoji-data.js', import.meta.url), out);
console.log(`${rows.length} emoji, ${owner.size} shortcodes, ${(out.length / 1024).toFixed(0)} KB`);
